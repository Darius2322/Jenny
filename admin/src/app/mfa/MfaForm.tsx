"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { createBrowserSupabase } from "@/lib/supabase-browser";

/** Staff must verify an authenticator-app code (TOTP) each session to reach aal2. First time: enrol, then verify. */
export function MfaForm() {
  const router = useRouter();
  const [factorId, setFactorId] = useState<string | null>(null);
  const [qr, setQr] = useState<string | null>(null);
  const [secret, setSecret] = useState<string | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const supabase = createBrowserSupabase();
    (async () => {
      const { data: factors, error: listErr } = await supabase.auth.mfa.listFactors();
      if (listErr) { setError("Couldn't load two-factor settings."); setReady(true); return; }
      const verified = factors?.totp?.find((f) => f.status === "verified");
      if (verified) { setFactorId(verified.id); setReady(true); return; }
      // Remove any abandoned, never-verified enrolment so a fresh one can be created.
      for (const f of factors?.all ?? []) if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      const { data, error: enrollErr } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "Jenny Admin" });
      if (enrollErr || !data) { setError("Couldn't start two-factor setup."); setReady(true); return; }
      setFactorId(data.id);
      setQr(data.totp.qr_code);
      setSecret(data.totp.secret);
      setReady(true);
    })();
  }, []);

  async function verify(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setBusy(true); setError(null);
    const supabase = createBrowserSupabase();
    const { error: vErr } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setBusy(false);
    if (vErr) { setError("That code didn't work. Check your authenticator app and try again."); return; }
    router.push("/");
    router.refresh();
  }

  if (!ready) return <p className="mt-6 text-sm text-muted">Loading…</p>;
  return (
    <form onSubmit={verify} className="mt-6 space-y-4">
      {qr && (
        <div className="space-y-2">
          <p className="text-sm">Scan this QR code with an authenticator app (Google Authenticator, Authy, 1Password…), then enter the 6-digit code.</p>
          {/* qr_code is an SVG data URI generated by Supabase Auth */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={qr} alt="Two-factor setup QR code" width={180} height={180} className="rounded-lg border border-line bg-white p-2" />
          {secret && <p className="break-all text-xs text-muted">Can&apos;t scan? Enter this key manually: <code>{secret}</code></p>}
        </div>
      )}
      <div>
        <label htmlFor="code" className="label">6-digit code</label>
        <input id="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required value={code} onChange={(e) => setCode(e.target.value)} className="field tracking-widest" />
      </div>
      {error && <p role="alert" className="text-sm font-medium text-red-600 dark:text-red-400">{error}</p>}
      <button type="submit" disabled={busy || !factorId} className="btn btn-primary w-full">{busy ? "Verifying…" : "Verify"}</button>
    </form>
  );
}
